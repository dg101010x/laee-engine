@dataclass(frozen=True)
class FeatureSpec:
    """Provenance of one generated column (spec §75).

    ``pattern`` is a regular expression matched against the whole column name. ``source``
    names the producing function and its inputs. ``availability`` says when the value is
    known relative to the row's ``date``. ``realtime_safe`` says whether it may be an input
    when predicting that date. ``retrospective`` marks values that depend on rows dated
    after the row itself; such a value stays unsafe even when lagged.
    """

    pattern: str
    source: str
    availability: str
    realtime_safe: bool
    retrospective: bool = False


_PAST_ONLY = "start of date: reads only rows dated before date"
_SAME_DAY = "end of date: summarises that day's own sales"
_IN_ADVANCE = "known in advance: a deterministic function of date"
_STOCK = "when the stock count is taken (start or end of date, see inventory_timing)"


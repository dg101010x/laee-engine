"""Leakage-safe temporal features and the generated-column registry (spec §74-75).

Calendar time, never row positions
----------------------------------
A 7-day lag is the value recorded exactly 7 calendar days earlier for the same series
(NaN when that day has no row). A 28-day rolling window aggregates the rows dated in
``[date - 28 days, date - 1 day]``. Gaps in a panel therefore never turn "7 days ago"
into "7 observations ago", and no feature attached to date ``d`` reads a row dated ``d``
or later. A feature computed on the full history thus equals the one available when
predicting ``d`` (spec §74).

Availability
------------
Panels built by :func:`laee.ingestion.to_daily_panel` carry ``available_at``, the end of
the sales day. :func:`as_of` keeps the rows with ``available_at <= prediction_time``
(spec §75). :data:`FEATURE_REGISTRY` records, for every column generated by
``laee.ingestion``, ``laee.normalization`` and ``laee.features``, where it comes from, when
it becomes known and whether it may feed a live prediction.

The column names shared across those subpackages are defined here, next to the
registry that documents them.
"""


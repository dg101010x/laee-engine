FEATURE_REGISTRY: dict[str, FeatureSpec] = {spec.pattern: spec for spec in _REGISTRY_ENTRIES}


def describe_feature(name: str) -> FeatureSpec:
    """Return the registry entry for a generated column name.

    A lag or rolling statistic inherits retrospectiveness from its base column, so
    ``promo_flag_lag_1d`` is not realtime-safe even though lags normally are.
    Raises ``KeyError`` for names that no registered pattern produces.
    """
    for spec in FEATURE_REGISTRY.values():
        match = re.fullmatch(spec.pattern, name)
        if match is None:
            continue
        base = match.groupdict().get("col")
        if base is None:
            return spec
        try:
            base_spec = describe_feature(base)
        except KeyError:
            return spec  # a raw panel column such as units or price
        if not base_spec.retrospective:
            return spec
        return replace(
            spec,
            availability=f"retrospective: inherits from {base} ({base_spec.availability})",
            realtime_safe=False,
            retrospective=True,
        )
    raise KeyError(f"{name!r} is not a registered generated column")


def lag_name(col: str, lag_days: int) -> str:
    """Column name produced by :func:`add_lag_features`."""
    return f"{col}_lag_{lag_days}d"


def rolling_name(col: str, stat: str, window_days: int) -> str:
    """Column name produced by :func:`add_rolling_features`."""
    return f"{col}_roll_{stat}_{window_days}d"


def require_columns(frame: pd.DataFrame, columns: Iterable[str]) -> None:
    """Raise ``KeyError`` naming every column of ``columns`` absent from ``frame``."""
    missing = [col for col in columns if col not in frame.columns]
    if missing:
        raise KeyError(f"missing required column(s): {', '.join(missing)}")


def series_keys(panel: pd.DataFrame) -> list[str]:
    """Series identifiers present in ``panel``: product_id plus business/location ids."""
    require_columns(panel, [PRODUCT_ID])
    return [key for key in SERIES_KEYS if key in panel.columns]


def normalize_dates(values: pd.Series | Iterable[object]) -> pd.Series:
    """Coerce dates to timezone-naive ``datetime64[ns]`` at midnight (wall-clock date kept)."""
    series = values if isinstance(values, pd.Series) else pd.Series(list(values))
    parsed = pd.to_datetime(series)
    if isinstance(parsed.dtype, pd.DatetimeTZDtype):
        parsed = parsed.dt.tz_localize(None)
    return parsed.dt.normalize().astype("datetime64[ns]")


def bool_column(frame: pd.DataFrame, col: str) -> np.ndarray:
    """``frame[col]`` as a bool array (missing -> False); all False when the column is absent.

    Strings count as true only for "true", "t", "yes", "y" or "1", so a CSV round trip
    of "False" stays False.
    """
    if col not in frame.columns:
        return np.zeros(len(frame), dtype=bool)
    series = frame[col]
    if pd.api.types.is_bool_dtype(series.dtype):
        return np.array(series.fillna(False), dtype=bool)  # a writable copy, not a CoW view
    return np.fromiter((_truthy(v) for v in series), dtype=bool, count=len(series))


def float_column(frame: pd.DataFrame, col: str) -> np.ndarray:
    """``frame[col]`` as a float array (unparseable -> NaN); all NaN when the column is absent."""
    if col not in frame.columns:
        return np.full(len(frame), np.nan)
    return _float_values(frame[col])


def map_unique(series: pd.Series, func: Callable[[object], object], missing: object = np.nan) -> pd.Series:
    """``series.map(func)`` evaluated once per distinct value; missing values give ``missing``.

    Exports repeat the same labels and flags thousands of times, so this is much faster
    than a per-row map. Values that hash equal (1, 1.0, True) share one result.
    """
    codes, uniques = pd.factorize(series, use_na_sentinel=True)
    mapped = np.array([func(value) for value in uniques] + [missing], dtype=object)
    return pd.Series(mapped[codes], index=series.index, name=series.name)  # code -1 -> missing


def ensure_unique_days(frame: pd.DataFrame, keys: Sequence[str]) -> None:
    """Raise ``ValueError`` unless ``frame`` has one row per (keys, date)."""
    duplicated = frame.duplicated(subset=[*keys, DATE])
    if duplicated.any():
        raise ValueError(
            f"{int(duplicated.sum())} row(s) repeat a ({', '.join([*keys, DATE])}) "
            "combination; a daily panel needs one row per series and day "
            "(pass every series key in `by`)"
        )


def group_positions(frame: pd.DataFrame, keys: Sequence[str]) -> list[np.ndarray]:
    """Positional row indices of each series in ``frame``, each sorted by date."""
    days = frame[DATE].to_numpy()
    groups = frame.groupby(list(keys), sort=False, dropna=False).indices
    return [pos[np.argsort(days[pos], kind="stable")] for pos in groups.values()]


def trailing_stat(
    panel: pd.DataFrame,
    col: str,
    window_days: int,
    *,
    by: str | Sequence[str] = PRODUCT_ID,
    stat: str = "mean",
    q: float | None = None,
    min_periods: int = 1,
) -> pd.Series:
    """``stat`` of ``col`` over each row's strictly-past calendar window.

    The window for a row dated ``d`` holds the same series' rows dated in
    ``[d - window_days, d)``. ``stat`` is one of :data:`ROLLING_STATS` or ``"quantile"``
    (with ``q``; the "higher" interpolation returns an observed value). NaN values are
    skipped. A window with fewer than ``min_periods`` values gives NaN, except for
    ``"count"``, which always returns the count.
    """
    keys = _as_list(by)
    require_columns(panel, [*keys, DATE, col])
    window = _positive_int(window_days, "window_days")
    _check_stat(stat, q)
    frame = panel[keys].copy()
    frame[DATE] = normalize_dates(panel[DATE])
    ensure_unique_days(frame, keys)
    values = _float_values(panel[col])
    result = _trailing(values, frame, keys, window, stat, q, min_periods)
    return pd.Series(result, index=panel.index, name=col)


def add_lag_features(
    panel: pd.DataFrame,
    cols: str | Sequence[str] = (UNITS, PRICE),
    lags_days: int | Sequence[int] = (1, 7),
    by: str | Sequence[str] = PRODUCT_ID,
) -> pd.DataFrame:
    """Add ``<col>_lag_<k>d``: the value of ``col`` exactly ``k`` calendar days earlier.

    Lags are matched on (by, date - k days), so a missing day yields NaN instead of
    silently borrowing an older row. Boolean columns are lagged as 0.0/1.0 floats.
    ``date`` is returned as ``datetime64[ns]`` at midnight.
    """
    keys = _as_list(by)
    columns = _as_list(cols)
    lags = [_positive_int(lag, "lags_days") for lag in _as_list(lags_days)]
    require_columns(panel, [*keys, DATE, *columns])
    overlap = set(columns) & {*keys, DATE}
    if overlap:
        raise ValueError(f"cannot lag key column(s): {', '.join(sorted(overlap))}")
    out = panel.copy()
    out[DATE] = normalize_dates(out[DATE])
    ensure_unique_days(out, keys)
    base = out[[*keys, DATE]].reset_index(drop=True)
    for lag in lags:
        shifted = out[[*keys, DATE, *columns]].reset_index(drop=True)
        shifted[DATE] = shifted[DATE] + pd.Timedelta(days=lag)
        merged = base.merge(shifted, on=[*keys, DATE], how="left", validate="one_to_one")
        for col in columns:
            lagged = merged[col]
            if pd.api.types.is_bool_dtype(out[col].dtype):
                lagged = lagged.astype("float64")
            out[lag_name(col, lag)] = lagged.to_numpy()
    return out


def add_rolling_features(
    panel: pd.DataFrame,
    col: str,
    windows_days: int | Sequence[int] = (7, 28),
    by: str | Sequence[str] = PRODUCT_ID,
    min_periods: int = 1,
    stats: str | Sequence[str] = ("mean",),
) -> pd.DataFrame:
    """Add ``<col>_roll_<stat>_<w>d`` over the ``w`` calendar days strictly before each row.

    Statistics aggregate the rows present in the window. Call
    :func:`laee.ingestion.fill_zero_sales_days` first if days without sales should count
    as zeros (e.g. for a units-per-day mean).
    """
    keys = _as_list(by)
    windows = [_positive_int(w, "windows_days") for w in _as_list(windows_days)]
    stat_list = _as_list(stats)
    for stat in stat_list:
        if stat not in ROLLING_STATS:
            raise ValueError(f"unknown stat {stat!r}; choose from {', '.join(ROLLING_STATS)}")
    require_columns(panel, [*keys, DATE, col])
    out = panel.copy()
    out[DATE] = normalize_dates(out[DATE])
    ensure_unique_days(out, keys)
    values = _float_values(out[col])
    for window in windows:
        for stat in stat_list:
            out[rolling_name(col, stat, window)] = _trailing(
                values, out, keys, window, stat, None, min_periods
            )
    return out


def as_of(
    df: pd.DataFrame,
    prediction_time: object,
    available_col: str = AVAILABLE_AT,
) -> pd.DataFrame:
    """Rows of ``df`` whose ``available_col`` is at or before ``prediction_time`` (spec §75).

    Rows with unknown availability (NaT) are excluded: they cannot be shown to be safe.
    """
    if available_col not in df.columns:
        raise KeyError(
            f"{available_col!r} column missing; leakage-safe filtering needs an explicit "
            "availability timestamp per row"
        )
    cutoff = pd.Timestamp(prediction_time)
    available = pd.to_datetime(df[available_col])
    aware = isinstance(available.dtype, pd.DatetimeTZDtype)
    if aware != (cutoff.tzinfo is not None):
        raise ValueError("prediction_time and available_at must both be timezone-aware or both naive")
    return df.loc[(available <= cutoff).to_numpy()].copy()


def _trailing(
    values: np.ndarray,
    frame: pd.DataFrame,
    keys: Sequence[str],
    window: int,
    stat: str,
    q: float | None,
    min_periods: int,
) -> np.ndarray:
    days = frame[DATE].to_numpy()
    result = np.full(len(frame), np.nan)
    for positions in group_positions(frame, keys):
        series = pd.Series(values[positions], index=pd.DatetimeIndex(days[positions]))
        # closed="left" makes the window [d - window, d): the row's own day is excluded.
        rolling = series.rolling(
            f"{window}D", closed="left", min_periods=0 if stat == "count" else min_periods
        )
        if stat == "quantile":
            aggregated = rolling.quantile(q, interpolation="higher")
        else:
            aggregated = getattr(rolling, stat)()
        result[positions] = aggregated.to_numpy()
    return result


def _check_stat(stat: str, q: float | None) -> None:
    if stat == "quantile":
        if q is None or not 0.0 <= q <= 1.0:
            raise ValueError("stat='quantile' needs q in [0, 1]")
    elif stat not in ROLLING_STATS:
        raise ValueError(f"unknown stat {stat!r}; choose from {', '.join(ROLLING_STATS)}, quantile")


def _truthy(value: object) -> bool:
    if isinstance(value, str):
        return value.strip().casefold() in {"true", "t", "yes", "y", "1"}
    if value is None or value is pd.NA or value is pd.NaT:
        return False
    if isinstance(value, (float, np.floating)) and np.isnan(value):
        return False
    try:
        return bool(value)
    except (TypeError, ValueError):
        return False


def _float_values(series: pd.Series) -> np.ndarray:
    """Writable float64 copy of ``series`` (pandas copy-on-write views are read-only)."""
    if pd.api.types.is_bool_dtype(series.dtype):
        return np.array(series, dtype="float64")
    return np.array(pd.to_numeric(series, errors="coerce"), dtype="float64")


def _as_list(value: object) -> list:
    if isinstance(value, (str, int, np.integer)):
        return [value]
    return list(value)  # type: ignore[call-overload]


def _positive_int(value: object, name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, (int, np.integer)) or value < 1:
        raise ValueError(f"{name} must contain positive integers (calendar days), got {value!r}")
    return int(value)
